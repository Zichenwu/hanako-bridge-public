/** 选语种：zh* → zh，其余 en。 */
function pickLang(nav) {
  const l = String((nav && nav.language) || "en").toLowerCase();
  return l.startsWith("zh") ? "zh" : "en";
}

const LANG = pickLang(typeof navigator !== "undefined" ? navigator : null);

/** 翻译；缺失 key 回落 en，再回落 key 本身（宁可显示 key 也不抛错）。 */
function t(key, vars) {
  let s = (MESSAGES[LANG] && MESSAGES[LANG][key]) ?? MESSAGES.en[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.split("{" + k + "}").join(String(vars[k]));
  return s;
}

/** 执行体 ID → Team 标签（`{team}--{user}` 的 team 段）。用户可见处一律用它，不显示 ID。 */
function teamOf(agentId) {
  const i = String(agentId || "").indexOf("--");
  return i > 0 ? agentId.slice(0, i) : String(agentId || "");
}

/** 把带 data-i18n 的节点填上文案。 */
function applyI18n(root) {
  (root || document).querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  document.documentElement.lang = LANG === "zh" ? "zh-CN" : "en";
}

if (typeof module !== "undefined") module.exports = { MESSAGES, t, teamOf, pickLang };
